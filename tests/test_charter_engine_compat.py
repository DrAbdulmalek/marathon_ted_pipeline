"""Charter ↔ engine compatibility tripwire.

Contract
--------
`config/marathon_ocr_rules.yaml` (rule R16) may require the visual-evidence gate
only if the ocr-core release pinned in `requirements.txt` actually implements it.
Flipping `require_visual_evidence` to `true` while the pinned engine ignores the
flag would silently mark ratio-derived labels as evidence-backed -- exactly the
training-data poisoning the charter exists to prevent.

This test is deterministic and offline: it reads the committed manifest
`docs/ocr_core_charter_compatibility.json` (generated by inspecting ocr-core's
release sources) and fails on any inconsistency.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "ocr_core_charter_compatibility.json"
RULES = ROOT / "config" / "marathon_ocr_rules.yaml"
REQS = ROOT / "requirements.txt"


def _manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))["releases"]


def _charter_requires_evidence() -> bool:
    cfg = yaml.safe_load(RULES.read_text(encoding="utf-8"))
    for rule in cfg.get("rules", []):
        if rule.get("id") == "R16":
            return bool(rule.get("params", {}).get("require_visual_evidence", False))
    raise AssertionError("R16 not found in marathon_ocr_rules.yaml")


def _pinned_tag() -> str:
    text = REQS.read_text(encoding="utf-8")
    m = re.search(r"ocr-core\.git@(?P<ref>[^\s#]+)", text)
    assert m, "ocr-core pin not found in requirements.txt"
    return m.group("ref")


def test_pinned_engine_supports_charter_gate():
    requires = _charter_requires_evidence()
    tag = _pinned_tag()
    rel = _manifest().get(tag)
    assert rel is not None, f"pinned ocr-core release {tag} missing from compatibility manifest"
    if requires:
        assert rel["engine_implements_visual_evidence_gate"], (
            f"charter requires require_visual_evidence=true but pinned {tag} "
            f"does not implement the gate -> labels would be ungrounded. "
            f"Pin a release with the gate (see docs/OCR_CORE_CHARTER_COMPATIBILITY.md) "
            f"or set require_visual_evidence: false and keep v1 behaviour explicit."
        )
    else:
        # Documented, intentional state: v1 ratio mode is explicit compatibility mode.
        assert requires is False


def test_manifest_covers_every_pinned_release():
    assert _pinned_tag() in _manifest()
